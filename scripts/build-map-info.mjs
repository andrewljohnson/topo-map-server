// Keep browser code literal: Hermes cannot stringify transpiled functions safely.
import fs from 'node:fs';
import {createRequire} from 'node:module';
const require=createRequire(new URL('../apps/web/package.json',import.meta.url));
const ts=require('typescript');
const source=fs.readFileSync(new URL('../apps/web/app/mapInfo.ts',import.meta.url),'utf8');
const code=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.ES2020}}).outputText.replace('export function installMapInfo','function installMapInfo');
fs.writeFileSync(new URL('../apps/mobile/src/mapInfo.ts',import.meta.url),'// Generated by scripts/build-map-info.mjs; do not stringify functions in Hermes.\nexport const mapInfoScript = '+JSON.stringify(code)+';\n');
