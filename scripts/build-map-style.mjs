// Keep web and the embedded mobile renderer on one cartographic style.
import fs from 'node:fs';
import {createRequire} from 'node:module';
const require=createRequire(new URL('../apps/web/package.json',import.meta.url));
const ts=require('typescript');
const source=fs.readFileSync(new URL('../apps/web/app/vectorStyle.ts',import.meta.url),'utf8');
fs.writeFileSync(new URL('../apps/mobile/src/vectorStyle.ts',import.meta.url),source);
fs.writeFileSync(new URL('../apps/mobile/src/style.mjs',import.meta.url),'// Generated by scripts/build-map-style.mjs. Edit apps/web/app/vectorStyle.ts.\n'+ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.ES2020}}).outputText);
